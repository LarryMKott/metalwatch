package service

// keySep 是复合键的分隔符：US（0x1f，ASCII 的 Unit Separator）。
//
// 用在两处：部件身份键（category + slot）与告警对象维度键（metric + object）。
// 两者都必须能与用户数据可靠区分开——主机名、磁盘型号里出现空格或冒号很常见，
// 控制字符则不会。
//
// 必须写成转义（"\x1f"）而不是把控制字节直接嵌进源码：本仓库已经因此出过一次
// 静默故障——同一分隔符在两个文件里一处是裸 0x1f 字节、一处是字面反斜杠转义，
// 于是两侧算出的键永不相等，映射查询恒为空。裸字节在编辑器、diff、格式化工具
// 往返中都可能被规范化掉，而肉眼完全看不出来；转义形式始终可读、可 diff、可 grep。
const keySep = "\x1f"
